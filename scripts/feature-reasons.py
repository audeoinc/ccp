items = collections.OrderedDict()
chapters = {}
for ln in open(STORIES, encoding='utf-8').read().splitlines():
    m = re.match(r'^## (\d+)\. (.+)$', ln)
    if m: chapters[int(m.group(1))] = m.group(2).strip()
    m = re.match(r'^- (✅|🟡|⬜) `(\d+)-(作|確)(\d+)` (.*)$', ln)
    if m:
        sid = f'{m.group(2)}-{m.group(3)}{m.group(4)}'
        text = re.sub(r'\s*※.*$', '', m.group(5)).strip()
        items[sid] = (m.group(1), text, int(m.group(2)))

fids = {f[0] for f in F}
impl = [k for k, v in items.items() if v[0] in '✅🟡']
missing = [k for k in impl if k not in M]
bad = [k for k in M if k not in items]
unknownF = sorted({x for v in M.values() for x in v} - fids)
if missing or bad or unknownF:
    print('missing', missing, 'bad', bad, 'unknownF', unknownF); sys.exit(1)
rev = collections.defaultdict(list)
for k, v in M.items():
    for f in v: rev[f].append(k)
unmapped_f = [f[0] for f in F if not rev.get(f[0])]

def sort_key(s):
    a, b = s.split('-'); return (int(a), 0 if b[0] == '作' else 1, int(b[1:]))

